def redact(text, cfg):
    result = str(text)
    env_path = Path(cfg.get("env_file", ""))
    if env_path.is_file():
        for line in env_path.read_text(encoding="utf-8", errors="replace").splitlines():
            if "=" in line:
                key, value = line.split("=", 1)
                if any(t in key.upper() for t in ("KEY", "TOKEN", "SECRET", "PASSWORD")):
                    value = value.strip().strip('"\'')
                    if value and len(value) >= 4:
                        result = result.replace(value, "[已隐藏]")
    for key, value in os.environ.items():
        if value and len(value) >= 8 and any(t in key.upper() for t in ("API_KEY", "SECRET", "ACCESS_TOKEN")):
            result = result.replace(value, "[已隐藏]")
    return result


def pid_alive(pid):
    if not pid:
        return False
    if os.name == "nt":
        # os.kill(pid, 0) can terminate processes on Windows; use a query handle.
        import ctypes
        from ctypes import wintypes
        kernel = ctypes.WinDLL("kernel32", use_last_error=True)
        kernel.OpenProcess.argtypes = [wintypes.DWORD, wintypes.BOOL, wintypes.DWORD]
        kernel.OpenProcess.restype = wintypes.HANDLE
        kernel.GetExitCodeProcess.argtypes = [wintypes.HANDLE, ctypes.POINTER(wintypes.DWORD)]
        kernel.GetExitCodeProcess.restype = wintypes.BOOL
        kernel.CloseHandle.argtypes = [wintypes.HANDLE]
        kernel.CloseHandle.restype = wintypes.BOOL
        handle = kernel.OpenProcess(0x1000, False, int(pid))
        if not handle:
            return False
        code = wintypes.DWORD()
        ok = kernel.GetExitCodeProcess(handle, ctypes.byref(code))
        kernel.CloseHandle(handle)
        return bool(ok and code.value == 259)
    try:
        os.kill(int(pid), 0)
        return True
    except ProcessLookupError:
        return False
    except PermissionError:
        return True


def busy(cfg):
    ps = paths(cfg)
    active = read_json(ps["active"])
    if not active.get("job_file"):
        return False
    job = read_json(active["job_file"])
    return job.get("status") in {"queued", "running"} and pid_alive(active.get("pid"))


def execute_stage(cfg, stage, state, query="", mode="qa"):
    ps = paths(cfg)
    for key in ["project", "source", "intermediate", "output", "results"]:
        ps[key].mkdir(parents=True, exist_ok=True)
    b = module(cfg, "build_demo")
    if stage == "pdf":
        src = require_file(state.get("source", {}).get("path", ""), "输入文献")
        if src.suffix.lower() == ".md":
            state["markdown"] = str(src)
            return dict(status="skipped", message="Markdown直接输入")
        converted = b.run_pdf_stage(src, ps["converted"], cfg["env_file"] or None,
                                   False, False, cfg["force_conversion"] or state.get("refresh_source_caches", False), "md_dollar")
        state["markdown"] = str(converted)
        return dict(path=str(converted), message="PDF转换完成")
    if stage == "clean":
        require_stage(state, "pdf")
        raw = require_file(state.get("markdown", ""), "Markdown文献")
        b.run_clean_stage(raw, ps["cleaned"])
        return dict(path=str(ps["cleaned"]), message="文本规范化完成")
    if stage == "json":
        require_stage(state, "clean")
        b.run_md_json_stage(require_file(ps["cleaned"], "规范化文本"), ps["structured"],
                            cfg["project_id"], state["source"]["name"])
        parsed = read_json(ps["structured"])
        if not parsed.get("sections"):
            raise ValueError("未识别出正文章节，请核对Markdown标题后重新解析。")
        return dict(path=str(ps["structured"]), processing_info=parsed.get("processing_info", {}))
    if stage == "graph":
        require_stage(state, "json")
        outputs = b.run_graph_stage(require_file(ps["structured"], "结构化JSON"), ps["output"],
                    cfg["project_id"], cfg["spacy_model"], cfg["embedding_model"],
                    cfg["max_chunk_tokens"], cfg["chunk_overlap"])
        return dict(outputs={k: str(v) for k, v in outputs.items()}, stats=read_json(ps["graph"]).get("stats", {}))
    if stage == "metadata":
        require_stage(state, "graph")
        summary = b.run_metadata_stage(require_file(ps["structured"], "结构化JSON"), ps["output"],
                   cfg["project_id"], cfg["env_file"] or None, cfg["metadata_model"],
                   cfg["embedding_model"], cfg["max_chunk_tokens"], False, cfg["force_metadata"] or state.get("refresh_source_caches", False))
        report = b.run_merge_stage(ps["graph"], ps["output"] / "metadata_node.json",
                                   ps["output"] / "metadata_merge_report.json")
        status = "warning" if summary.get("fallback_used") or (not summary.get("cache_hit") and not summary.get("json_parsed")) else "success"
        return dict(status=status, summary=summary, merge_report=report,
                    message="请核对回退的元数据内容" if status == "warning" else "元数据处理完成")
    if stage == "index":
        require_stage(state, "graph")
        manifest = b.run_embedding_stage(ps["output"], cfg["embedding_model"], cfg["device"], False)
        return dict(manifest=manifest, graph_sha256=digest(ps["graph"]), message="向量索引创建完成")
    if stage == "qa":
        require_stage(state, "index")
        index = read_json(require_file(ps["index"], "向量索引清单"))
        model = index.get("embedding", {}).get("model")
        if model != cfg["embedding_model"]:
            raise ValueError("查询嵌入模型与索引模型不一致，请恢复建库模型或重新创建索引。")
        saved_hash = state.get("steps", {}).get("index", {}).get("graph_sha256")
        if saved_hash and saved_hash != digest(ps["graph"]):
            raise ValueError("图谱已经修改，请重新创建索引后问答。")
        if not query.strip():
            raise ValueError("请先输入问题。")
        m = module(cfg, "main_pipeline")
        configuration = m.PipelineConfig(output_dir=str(ps["output"]), embedding_model_path=cfg["embedding_model"],
            rerank_model_path=cfg["rerank_model"], env_file_path=cfg["env_file"], llm_model_name=cfg["llm_model"],
            device=cfg["device"], retrieval_top_k=cfg["retrieval_top_k"], rerank_top_n=cfg["rerank_top_n"],
            max_evidence_objects=cfg["max_evidence_objects"], max_textual_evidence_tokens=cfg["max_textual_tokens"],
            max_visual_tabular_items=cfg["max_visual_tabular_items"], enable_multimodal=cfg["multimodal"],
            asset_base_dir=cfg["asset_base_dir"], allow_generation_fallback=False)
        pipeline, graph = m.build_pipeline_from_output_dir(configuration)
        result = pipeline.run(query=query, graph=graph, task_mode=mode)
        result["gui_provenance"] = {"source_sha256": state.get("source", {}).get("sha256"),
                                    "graph_sha256": digest(ps["graph"]), "created_at": now()}
        dst = ps["results"] / f"{datetime.now():%Y%m%d_%H%M%S}_{mode}_{uuid.uuid4().hex[:6]}.json"
        write_json(dst, result)
        state["last_result"] = str(dst)
        return dict(path=str(dst), mode=mode, message="回答已生成" if mode == "qa" else "抽取已完成")
    raise ValueError(f"Unknown stage: {stage}")


def worker(job_file):
    job_file = Path(job_file); job = read_json(job_file); cfg = job["config"]; ps = paths(cfg)
    ps["project"].mkdir(parents=True, exist_ok=True)
    acquired = False
    # An abandoned lock is removed only when its owning process is gone.
    if ps["lock"].exists() and not pid_alive(read_json(ps["lock"]).get("pid")):
        ps["lock"].unlink(missing_ok=True)
    try:
        with ps["lock"].open("x", encoding="utf-8") as lock:
            json.dump({"pid": os.getpid(), "job_file": str(job_file)}, lock)
        acquired = True
        job.update(status="running", started_at=now(), completed=0, total=len(job["stages"]))
        write_json(job_file, job)
        state = read_json(ps["manifest"])
        for stage in job["stages"]:
            job["current"] = stage; write_json(job_file, job)
            invalidate(state, stage)
            state.setdefault("steps", {})[stage] = dict(status="running", at=now())
            write_json(ps["manifest"], state)
            print(f"\n[开始] {STAGES[stage]}", flush=True)
            try:
                report = execute_stage(cfg, stage, state, job.get("query", ""), job.get("mode", "qa"))
            except Exception:
                state["steps"][stage] = dict(status="failed", at=now())
                write_json(ps["manifest"], state)
                raise
            report.setdefault("status", "success"); report["at"] = now()
            state["steps"][stage] = report; write_json(ps["manifest"], state)
            job["completed"] += 1; write_json(job_file, job)
            print(f"[结束] {STAGES[stage]}：{report['status']}", flush=True)
        job.update(status="success", finished_at=now()); write_json(job_file, job)
        return 0
    except Exception as exc:
        error = redact(str(exc), cfg)
        if isinstance(exc, ModuleNotFoundError):
            error = f"缺少Python依赖 {exc.name}。请安装requirements-full.txt及科学分句模型。"
        job.update(status="failed", finished_at=now(), error=error); write_json(job_file, job)
        print(redact(traceback.format_exc(), cfg), flush=True)
        return 1
    finally:
        if acquired:
            ps["lock"].unlink(missing_ok=True)


def begin_job(cfg, stages, query="", mode="qa"):
    if busy(cfg):
        raise RuntimeError("当前任务正在运行，请等待完成。")
    ps = paths(cfg); directory = ps["project"] / "jobs"; directory.mkdir(parents=True, exist_ok=True)
    job_file = directory / f"{datetime.now():%Y%m%d_%H%M%S}_{uuid.uuid4().hex[:8]}.json"
    log = job_file.with_suffix(".log")
    write_json(job_file, dict(config=cfg, stages=stages, query=query, mode=mode, status="queued", created_at=now()))
    with log.open("w", encoding="utf-8") as stream:
        child = subprocess.Popen([sys.executable, "-u", str(Path(__file__).resolve()), "--worker", str(job_file)],
                                  stdout=stream, stderr=subprocess.STDOUT, cwd=ROOT)
    write_json(ps["active"], dict(pid=child.pid, job_file=str(job_file), log_file=str(log)))
    return child


